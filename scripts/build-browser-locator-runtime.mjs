#!/usr/bin/env node

import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const locatorDir = path.join(repoRoot, "plugins/browser-bridge/apps/cli/internal/locator");
const sourceDir = path.join(locatorDir, "runtime-src");
const outputPath = path.join(locatorDir, "generated/runtime.js");
const requireFromDesktop = createRequire(path.join(repoRoot, "packages/desktop/package.json"));
const esbuild = requireFromDesktop("esbuild");

const sourceFiles = readdirSync(sourceDir)
  .filter((name) => name.endsWith(".ts"))
  .sort()
  .map((name) => path.join(sourceDir, name));
const sourceHash = createHash("sha256");
for (const file of sourceFiles) {
  sourceHash.update(path.basename(file));
  sourceHash.update("\0");
  sourceHash.update(readFileSync(file));
  sourceHash.update("\0");
}
const buildHash = sourceHash.digest("hex");

const result = await esbuild.build({
  entryPoints: [path.join(sourceDir, "index.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["chrome120"],
  write: false,
  legalComments: "none",
  define: {
    __ACTSPACE_LOCATOR_BUILD_HASH__: JSON.stringify(buildHash),
  },
  banner: {
    js: `/* Generated by scripts/build-browser-locator-runtime.mjs. Source hash: ${buildHash}. */`,
  },
});

const generated = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== generated) {
    throw new Error("generated Browser Locator Runtime is stale; run node scripts/build-browser-locator-runtime.mjs");
  }
  process.stdout.write(`browser locator runtime build check passed (${buildHash.slice(0, 12)})\n`);
} else {
  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, generated);
  process.stdout.write(`updated ${path.relative(repoRoot, outputPath)} (${buildHash.slice(0, 12)})\n`);
}
