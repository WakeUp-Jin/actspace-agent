import { readFile, writeFile, mkdir, rename } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { createRequire } from "node:module";
const ts = createRequire(new URL("../packages/shared/package.json", import.meta.url))("typescript");

const root = resolve(import.meta.dirname, "..");
const source = await readFile(resolve(root, "packages/shared/src/model-catalog-normalize.ts"), "utf8");
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const { normalizeModelCatalog } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`);
const urls = { "models.dev": "https://models.dev/api.json", openrouter: "https://openrouter.ai/api/v1/models" };
const entries = [];
for (const [name, url] of Object.entries(urls)) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  entries.push(...normalizeModelCatalog(name, await response.json()));
}
const snapshot = { schemaVersion: 1, generatedAt: new Date().toISOString(), contentHash: createHash("sha256").update(JSON.stringify(entries)).digest("hex"), entries };
const target = resolve(root, "packages/shared/src/generated/model-catalog.generated.ts");
await mkdir(dirname(target), { recursive: true });
await writeFile(`${target}.tmp`, `// Generated by pnpm models:generate. Do not edit prices by hand.\nimport type { ModelCatalogSnapshot } from "../model-catalog";\nexport const BUILTIN_MODEL_CATALOG: ModelCatalogSnapshot = ${JSON.stringify(snapshot)};\n`);
await rename(`${target}.tmp`, target);
console.log(`Generated ${entries.length} model facts (${snapshot.contentHash.slice(0, 12)})`);
