#!/usr/bin/env node

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cliDir = path.join(repoRoot, "plugins/browser-bridge/apps/cli");
const generatedPath = path.join(
  repoRoot,
  "packages/agent-core/src/tools/tools/browser/generated-actions.ts",
);
const commandSurfacePath = path.join(
  repoRoot,
  "docs/design-docs/agent-browser-use-command-surface.md",
);

const raw = execFileSync("go", ["run", ".", "commands", "--json"], {
  cwd: cliDir,
  encoding: "utf8",
  env: { ...process.env, GOCACHE: process.env.GOCACHE || "/private/tmp/abb-go-cache" },
});
const report = JSON.parse(raw);

const expectedCounts = {
  cua: 9,
  dom: 7,
  locator: 21,
  navigation: 4,
  tabs: 6,
  user: 3,
  wait: 5,
  io: 6,
  debug: 1,
};

if (report.count !== 62 || report.commands.length !== 62) {
  throw new Error(`registry must contain 62 commands, got ${report.count}/${report.commands.length}`);
}

for (const [category, expected] of Object.entries(expectedCounts)) {
  const actual = report.commands.filter((command) => command.category === category).length;
  if (actual !== expected) {
    throw new Error(`category ${category} must contain ${expected} commands, got ${actual}`);
  }
}

const requiredFields = [
  "id",
  "category",
  "action",
  "description",
  "inputSchema",
  "outputSchema",
  "backendRequirements",
  "requiredCapabilities",
  "riskLevel",
  "readOnly",
  "effect",
  "originPolicy",
  "previewKind",
  "status",
  "examples",
];
for (const command of report.commands) {
  for (const field of requiredFields) {
    if (!(field in command) || command[field] === "") {
      throw new Error(`command ${command.id || "<unknown>"} is missing ${field}`);
    }
  }
}

const surface = readFileSync(commandSurfacePath, "utf8");
const documentedIDs = [...surface.matchAll(/^### ([a-z][a-z0-9_]*)$/gm)].map((match) => match[1]);
const registryIDs = report.commands.map((command) => command.id);
const documentedSet = new Set(documentedIDs);
const registrySet = new Set(registryIDs);
const missingFromRegistry = documentedIDs.filter((id) => !registrySet.has(id));
const missingFromDocs = registryIDs.filter((id) => !documentedSet.has(id));
if (documentedIDs.length !== 62 || missingFromRegistry.length || missingFromDocs.length) {
  throw new Error(
    [
      `command surface must document exactly 62 command headings, got ${documentedIDs.length}`,
      `missing from registry: ${missingFromRegistry.join(", ") || "none"}`,
      `missing from docs: ${missingFromDocs.join(", ") || "none"}`,
    ].join("\n"),
  );
}

const generatedMetadata = report.commands.map((command) => ({
  id: command.id,
  category: command.category,
  action: command.action,
  riskLevel: command.riskLevel,
  readOnly: command.readOnly,
  effect: command.effect,
  originPolicy: command.originPolicy,
  previewKind: command.previewKind,
  backendRequirements: command.backendRequirements,
  requiredCapabilities: command.requiredCapabilities,
  status: command.status,
  legacyAliases: command.legacyAliases || [],
}));

const actionsByCategory = Object.fromEntries(
  Object.keys(expectedCounts).map((category) => [
    category,
    generatedMetadata
      .filter((command) => command.category === category)
      .map((command) => command.action),
  ]),
);
const legacyAliases = Object.fromEntries(
  generatedMetadata.flatMap((command) =>
    command.legacyAliases.map((alias) => [
      alias,
      { category: command.category, action: command.action, commandId: command.id },
    ]),
  ),
);
const hash = createHash("sha256").update(JSON.stringify(generatedMetadata)).digest("hex");

const generated = `// Generated by scripts/check-browser-command-registry.mjs --write. Do not edit manually.\n\nexport const browserCommandRegistryVersion = ${JSON.stringify(report.version)};\nexport const browserCommandRegistryHash = ${JSON.stringify(hash)};\n\nexport const browserCommandMetadata = ${JSON.stringify(generatedMetadata, null, 2)} as const;\n\nexport const browserActionsByCategory = ${JSON.stringify(actionsByCategory, null, 2)} as const;\n\nexport const browserLegacyAliases = ${JSON.stringify(legacyAliases, null, 2)} as const;\n\nexport type BrowserCommandMetadata = (typeof browserCommandMetadata)[number];\nexport type BrowserCategory = BrowserCommandMetadata["category"];\nexport type BrowserAction = BrowserCommandMetadata["action"];\n`;

if (process.argv.includes("--write")) {
  writeFileSync(generatedPath, generated);
  process.stdout.write(`updated ${path.relative(repoRoot, generatedPath)}\n`);
} else {
  const current = readFileSync(generatedPath, "utf8");
  if (current !== generated) {
    throw new Error(
      "generated browser action metadata is stale; run node scripts/check-browser-command-registry.mjs --write",
    );
  }
  process.stdout.write("browser command registry check passed\n");
}
